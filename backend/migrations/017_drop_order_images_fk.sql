-- 电脑维修店报修系统 —— 迁移脚本 017
-- 目标: 解除 order_images.order_id 对 repair_orders 的外键约束
-- 原因:
--   预上传（temporary）图片在工单落库前即可存在，此时 order_id 尚未确定，
--   用哨兵值 00000000-0000-0000-0000-000000000000 占位的"未绑定"图片不应被
--   外键约束拒绝（否则上传即报 23503）。
-- 设计权衡:
--   - 仅 active 图片计入工单真实图片数；active 图片在提交/保存时必回填真实 order_id，
--     因此外键约束在此并非必需。
--   - 保留列上的 NOT NULL，强制 active 图片必须归属某个工单。
--   - ON DELETE CASCADE 随之失效：本系统工单走状态机（不硬删除），图片生命周期
--     由 status(temporary/active/deleted) 软标记管理，删除工单时由业务层清理，影响可控。
-- 版本: V1.5 (预上传 + 临时标记 + 提交时关联)
-- =============================================================================

ALTER TABLE order_images
    DROP CONSTRAINT IF EXISTS order_images_order_id_fkey;
